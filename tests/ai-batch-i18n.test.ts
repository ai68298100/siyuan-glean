test("批量 AI 双语交接清单的键集合、非空文案和插值一致", () => {
    assert.deepEqual(Object.keys(aiBatchTranslations.zh_CN).sort(), Object.keys(aiBatchTranslations.en_US).sort());
    for (const key of Object.keys(aiBatchTranslations.zh_CN) as (keyof typeof aiBatchTranslations.zh_CN)[]) {
        const chinese = aiBatchTranslations.zh_CN[key];
        const english = aiBatchTranslations.en_US[key];
        assert.ok(chinese.trim() && english.trim());
        assert.deepEqual([...chinese.matchAll(/\$\{(\w+)\}/g)].map((match) => match[1]).sort(), [...english.matchAll(/\$\{(\w+)\}/g)].map((match) => match[1]).sort(), key);
    }
});
